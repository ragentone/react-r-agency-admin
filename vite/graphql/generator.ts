import {
  type GraphQLArgument,
  type GraphQLEnumType,
  type GraphQLField,
  type GraphQLInputField,
  type GraphQLInputObjectType,
  type GraphQLInterfaceType,
  type GraphQLNamedType,
  type GraphQLObjectType,
  type GraphQLSchema,
  type GraphQLType,
  type GraphQLUnionType,
  isEnumType,
  isInputObjectType,
  isInterfaceType,
  isListType,
  isNonNullType,
  isObjectType,
  isScalarType,
  isSpecifiedScalarType,
  isUnionType,
} from 'graphql';

import type { IGeneratedFiles, IResolvedGraphqlTypesOptions } from './types.ts';

/** Output files (index.ts re-exports them alphabetically). */
const FILES: FileKey[] = ['scalars', 'enums', 'inputs', 'objects', 'args'];

const BUILTIN_SCALARS: Record<string, string> = {
  String: 'string',
  Int: 'number',
  Float: 'number',
  Boolean: 'boolean',
};

export const DEFAULT_SCALARS: Record<string, string> = {
  ID: 'string | number',
  JSON: 'any',
  JSONObject: 'Record<string, any>',
  DateTime: 'string',
  Date: 'string',
  Time: 'string',
  Email: 'string',
  Password: 'string',
  URL: 'string',
  UUID: 'string',
  BigInt: 'string',
  Upload: 'File | Blob',
  Void: 'void',
};

const HEADER = [
  '// ----------------------------------------------------------------------------',
  '// AUTO-GENERATED by vite/graphql (graphqlTypesPlugin) – do not edit by hand.',
  '// Changes are overwritten whenever the GraphQL schema changes.',
  '// ----------------------------------------------------------------------------',
  '',
].join('\n');

/** `dbFilter_enum` → `DbFilterEnum`, `userGetById` → `UserGetById` */
export function pascalCase(name: string): string {
  return name
    .split(/[_\-\s]+/)
    .filter(Boolean)
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function jsDoc(lines: (string | null | undefined)[], indent = ''): string {
  const content = lines
    .filter((l): l is string => typeof l === 'string' && l.trim() !== '')
    .flatMap(l => l.replace(/\*\//g, '*\\/').split('\n'))
    .map(l => l.trimEnd());
  if (!content.length) return '';
  if (content.length === 1) return `${indent}/** ${content[0]} */\n`;
  return `${indent}/**\n${content.map(l => `${indent} * ${l}`.trimEnd()).join('\n')}\n${indent} */\n`;
}

function deprecated(reason: string | null | undefined): string | null {
  if (reason === undefined || reason === null) return null;
  return `@deprecated ${reason}`.trim();
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (name: string) => (IDENT.test(name) ? name : JSON.stringify(name));

export type FileKey = 'scalars' | 'enums' | 'inputs' | 'objects' | 'args';

export interface INameEntry {
  tsName: string;
  file: FileKey;
}

/** Sorted schema types (without `__*` introspection types). */
export function schemaTypes(schema: GraphQLSchema): GraphQLNamedType[] {
  return Object.values(schema.getTypeMap())
    .filter(t => !t.name.startsWith('__'))
    .sort((a, b) => a.name.localeCompare(b.name));
}

/** GraphQL type name → generated TS name + target file. */
export function createNameRegistry(
  schema: GraphQLSchema,
  options: IResolvedGraphqlTypesOptions
): Map<string, INameEntry> {
  const types = schemaTypes(schema);
  // ---------------------------------------------------------------- naming
  /** GraphQL name → { TS name, file } */
  const registry = new Map<string, INameEntry>();
  const used = new Set<string>();

  const register = (type: GraphQLNamedType, file: FileKey, tsName: string) => {
    let name = tsName;
    for (let i = 2; used.has(name); i++) name = `${tsName}${i}`;
    if (name !== tsName) {
      console.warn(`--- [GRAPHQL-TYPES] name clash: "${type.name}" generated as "${name}"`);
    }
    used.add(name);
    registry.set(type.name, { tsName: name, file });
  };

  for (const type of types) {
    if (isScalarType(type)) {
      if (!isSpecifiedScalarType(type) || type.name === 'ID') {
        register(type, 'scalars', `Scalar${pascalCase(type.name)}`);
      }
    } else if (isEnumType(type)) register(type, 'enums', pascalCase(type.name));
    else if (isInputObjectType(type))
      register(type, 'inputs', options.prefix + pascalCase(type.name));
    else if (isUnionType(type)) register(type, 'objects', pascalCase(type.name));
    else register(type, 'objects', options.prefix + pascalCase(type.name));
  }

  return registry;
}

export function generateTypes(
  schema: GraphQLSchema,
  options: IResolvedGraphqlTypesOptions
): IGeneratedFiles {
  const scalarMap = { ...DEFAULT_SCALARS, ...options.scalars };
  const types = schemaTypes(schema);

  const registry = createNameRegistry(schema, options);

  // ---------------------------------------------------------------- imports
  const imports: Record<FileKey, Map<FileKey, Set<string>>> = {
    scalars: new Map(),
    enums: new Map(),
    inputs: new Map(),
    objects: new Map(),
    args: new Map(),
  };
  const ref = (from: FileKey, name: string): string => {
    const reg = registry.get(name);
    if (!reg) return BUILTIN_SCALARS[name] ?? 'unknown';
    if (reg.file !== from) {
      const set = imports[from].get(reg.file) ?? new Set<string>();
      set.add(reg.tsName);
      imports[from].set(reg.file, set);
    }
    return reg.tsName;
  };

  const renderType = (
    type: GraphQLType,
    from: FileKey,
    input: boolean,
    nullable = true
  ): string => {
    if (isNonNullType(type)) return renderType(type.ofType, from, input, false);
    let ts: string;
    if (isListType(type)) ts = `Array<${renderType(type.ofType, from, input)}>`;
    else ts = ref(from, (type as GraphQLNamedType).name);
    if (!nullable) return ts;
    return `${ref(from, input ? '__InputMaybe' : '__Maybe')}<${ts}>`;
  };
  // helper types live in scalars.ts
  registry.set('__Maybe', { tsName: 'Maybe', file: 'scalars' });
  registry.set('__InputMaybe', { tsName: 'InputMaybe', file: 'scalars' });

  const renderField = (
    field: GraphQLField<unknown, unknown> | GraphQLInputField | GraphQLArgument,
    from: FileKey,
    input: boolean
  ): string => {
    const optional =
      !isNonNullType(field.type) &&
      (input ? options.optionalInputFields : options.optionalOutputFields);
    const def =
      'defaultValue' in field && field.defaultValue !== undefined
        ? `@default ${JSON.stringify(field.defaultValue)}`
        : null;
    return (
      jsDoc([field.description, def, deprecated(field.deprecationReason)], '  ') +
      `  ${key(field.name)}${optional ? '?' : ''}: ${renderType(field.type, from, input)};\n`
    );
  };

  // ---------------------------------------------------------------- bodies
  const body: Record<FileKey, string[]> = {
    scalars: [
      `export type Maybe<T> = ${options.maybeValue};\n`,
      `export type InputMaybe<T> = ${options.inputMaybeValue};\n`,
    ],
    enums: [],
    inputs: [],
    objects: [],
    args: [],
  };

  for (const type of types) {
    const reg = registry.get(type.name);
    if (!reg) continue;
    const doc = jsDoc([type.description, `GraphQL: \`${type.name}\``]);

    if (isScalarType(type)) {
      const ts = scalarMap[type.name] ?? options.defaultScalarType;
      body.scalars.push(`${doc}export type ${reg.tsName} = ${ts};\n`);
    } else if (isEnumType(type)) {
      body.enums.push(renderEnum(type, reg.tsName, doc));
    } else if (isInputObjectType(type)) {
      body.inputs.push(renderInput(type, reg.tsName, doc));
    } else if (isUnionType(type)) {
      body.objects.push(renderUnion(type, reg.tsName, doc));
    } else if (isObjectType(type) || isInterfaceType(type)) {
      body.objects.push(renderObject(type, reg.tsName, doc));
      if (options.args) body.args.push(...renderArgs(type, reg.tsName));
    }
  }

  function renderEnum(type: GraphQLEnumType, name: string, doc: string): string {
    const values = type.getValues();
    const union = values.length ? values.map(v => `'${v.name}'`).join(' | ') : 'never';
    const entries = values
      .map(
        v =>
          jsDoc([v.description, deprecated(v.deprecationReason)], '  ') +
          `  ${key(v.name)}: '${v.name}',\n`
      )
      .join('');
    // union type + const object instead of a TS `enum` (tsconfig: erasableSyntaxOnly)
    return (
      `${doc}export type ${name} = ${union};\n` +
      `${doc}export const ${name} = {\n${entries}} as const;\n`
    );
  }

  function renderInput(type: GraphQLInputObjectType, name: string, doc: string): string {
    const fields = Object.values(type.getFields())
      .map(f => renderField(f, 'inputs', true))
      .join('');
    return `${doc}export interface ${name} {\n${fields}}\n`;
  }

  function renderUnion(type: GraphQLUnionType, name: string, doc: string): string {
    const members = type.getTypes().map(t => ref('objects', t.name));
    return `${doc}export type ${name} = ${members.join(' | ') || 'never'};\n`;
  }

  function renderObject(
    type: GraphQLObjectType | GraphQLInterfaceType,
    name: string,
    doc: string
  ): string {
    let fields = '';
    if (options.typename && isObjectType(type)) fields += `  __typename?: '${type.name}';\n`;
    fields += Object.values(type.getFields())
      .map(f => renderField(f, 'objects', false))
      .join('');
    const kind = isInterfaceType(type) ? `GraphQL interface \`${type.name}\`` : null;
    const docWithKind = kind ? jsDoc([type.description, kind]) : doc;
    return `${docWithKind}export interface ${name} {\n${fields}}\n`;
  }

  function renderArgs(type: GraphQLObjectType | GraphQLInterfaceType, name: string): string[] {
    return Object.values(type.getFields())
      .filter(f => f.args.length)
      .map(f => {
        const argsName = `${name}${pascalCase(f.name)}Args`;
        const fields = f.args.map(a => renderField(a, 'args', true)).join('');
        return `${jsDoc([`Arguments of \`${type.name}.${f.name}\``])}export interface ${argsName} {\n${fields}}\n`;
      });
  }

  // ---------------------------------------------------------------- files
  const files: IGeneratedFiles = {};
  for (const file of FILES) {
    const importLines = [...imports[file].entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(
        ([source, names]) => `import type { ${[...names].sort().join(', ')} } from './${source}';\n`
      )
      .join('');
    const content = body[file].length ? body[file].join('\n') : 'export {};\n';
    files[`${file}.ts`] = `${HEADER}\n${importLines}${importLines ? '\n' : ''}${content}`;
  }
  files['index.ts'] = `${HEADER}\n${[...FILES]
    .sort()
    .map(f => `export * from './${f}';`)
    .join('\n')}\n`;
  return files;
}
