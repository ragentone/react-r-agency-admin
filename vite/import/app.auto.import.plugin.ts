// noinspection PointlessBooleanExpressionJS

import { existsSync, mkdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

import fs from 'fs/promises';
import { glob } from 'glob';
import type { Plugin } from 'vite';

import type { IConfig, IGlobalBuildConfig, IOptions } from './types.ts';

const PATTERN: string[] = ['**/config.json'];

export function autoImportPlugin(options: IOptions = {}): Plugin {
  const { targetDir = 'src', exclude = ['**/*.d.ts', '**/*.test.ts', '**/*.spec.ts'] } = options;
  const targetDirs = (Array.isArray(targetDir) ? targetDir : [targetDir]).filter(Boolean);
  let buildConfig: IGlobalBuildConfig = {
    disabled: [],
    modes: {},
  };
  /** Vite mode (`development`, `production`, …) – set in `configResolved`. */
  let mode = 'development';

  /** Why a module is skipped in the current mode, or `null` when it is built. */
  const skipReason = (config: IConfig): string | null => {
    if (buildConfig.disabled?.includes(config.name)) return 'build.config.json → disabled';
    if (buildConfig.modes?.[mode]?.disabled?.includes(config.name)) {
      return `build.config.json → modes.${mode}.disabled`;
    }
    if (config.modes?.length && !config.modes.includes(mode)) {
      return `config.json → modes [${config.modes.join(', ')}]`;
    }
    return null;
  };

  async function loadGlobalConfig() {
    try {
      const confPath = path.resolve(__dirname, '../../build.config.json');
      if (!existsSync(confPath)) {
        return;
      }
      // Start from the defaults on every (re)load, so removed entries really disappear.
      buildConfig = { disabled: [], modes: {}, ...JSON.parse(readFileSync(confPath, 'utf8')) };
    } catch (e) {
      const error = e as Error;
      console.error(error.message);
    }
  }

  async function scanAndGenerateImports(scanDir: string) {
    const files = await glob(PATTERN, {
      cwd: scanDir,
      ignore: exclude,
      absolute: true,
    });

    const configs: (IConfig | undefined)[] = files.map(file => {
      try {
        const json = readFileSync(file, 'utf8');
        const config: IConfig = JSON.parse(json);
        if (!config.name) {
          return undefined;
        }

        if (config.active === false) {
          return undefined;
        }

        const reason = skipReason(config);
        if (reason) {
          console.log(`--- [AUTO-IMPORT] ${config.name} – skipped in "${mode}" (${reason})`);
          return undefined;
        }

        console.log(`--- [AUTO-IMPORT] ${config.name}`);

        config.dir = path.dirname(file);
        config.sortOrder ??= 0;
        config.active ??= false;
        return config;
      } catch (e) {
        console.error((e as Error).message);
        return undefined;
      }
    });

    const sorted = configs
      .filter(config => typeof config === 'object')
      .filter(config => config?.active)
      .sort((a, b) => (a!.sortOrder ?? 0) - (b!.sortOrder ?? 0)) as IConfig[];

    if (sorted.length === 0) {
      return '';
    }

    const targetDirAbs = path.resolve(process.cwd(), scanDir);
    const importLines: string[] = [];

    sorted.forEach(config => {
      config.entries.map(entry => {
        const _pathAbs = path.resolve(config.dir, entry);
        if (existsSync(_pathAbs)) {
          let relativePath = path.relative(targetDirAbs, _pathAbs).split(path.sep).join('/');
          if (!relativePath.startsWith('.')) {
            relativePath = './' + relativePath;
          }
          importLines.push(`import "${relativePath}"`);
        }
      });
    });

    if (importLines.length === 0) {
      return '';
    }

    const banner: string[] = [
      '',
      `// ---- Powered by r-agency.org`,
      `// ---- This file is auto-generated by vite-plugin-auto-import. Do not edit manually.`,
      // No timestamp: the file only changes when the imports change (no git noise, no
      // needless file-change event on every dev server start).
    ];

    return [...banner, ...importLines].join('\n');
  }

  const ensureDir = (dir: string) => {
    const abs = path.resolve(process.cwd(), dir);
    if (!existsSync(abs)) {
      mkdirSync(abs, { recursive: true });
    }
  };

  /** Writes `<dir>/imports.ts` only if the content changed. Returns true when written. */
  const writeTargetFile = async (dir: string, content: string) => {
    const targetPathAbs = path.resolve(process.cwd(), dir, 'imports.ts');
    const current = existsSync(targetPathAbs) ? readFileSync(targetPathAbs, 'utf8') : null;
    if (current === content) return false;
    await fs.writeFile(targetPathAbs, content, 'utf-8');
    return true;
  };

  const generateAll = async () => {
    await loadGlobalConfig();
    for (const dir of targetDirs) {
      ensureDir(dir);
      const content = await scanAndGenerateImports(dir);
      if (await writeTargetFile(dir, content)) {
        console.log(`--- [AUTO-IMPORT] ${dir}/imports.ts updated`);
      }
    }
  };

  const globalConfigPath = path.resolve(__dirname, '../../build.config.json');
  const targetDirsAbs = () => targetDirs.map(dir => path.resolve(process.cwd(), dir) + path.sep);
  /** `config.json` of a module/app inside one of the target dirs, or the global build.config.json. */
  const isRelevantFile = (file: string) =>
    path.resolve(file) === globalConfigPath ||
    (path.basename(file) === 'config.json' &&
      targetDirsAbs().some(dir => path.resolve(file).startsWith(dir)));

  return {
    name: 'vite-plugin-auto-import',
    configResolved(resolved) {
      mode = resolved.mode;
    },
    async buildStart() {
      await generateAll();
    },
    /**
     * Dev server: regenerate when a module `config.json` or `build.config.json` is added,
     * changed or removed – no restart needed. A changed `imports.ts` makes Vite reload the page.
     */
    configureServer(server) {
      server.watcher.add(globalConfigPath);
      let queued: ReturnType<typeof setTimeout> | undefined;
      const onFile = (file: string) => {
        if (!isRelevantFile(file)) return;
        clearTimeout(queued);
        queued = setTimeout(() => {
          generateAll().catch(e => console.error((e as Error).message));
        }, 100);
      };
      server.watcher.on('add', onFile);
      server.watcher.on('change', onFile);
      server.watcher.on('unlink', onFile);
    },
  };
}
